const RECENT_KEY = "ft-recent-emoji";
/** How many are kept in the first tab. */
export const RECENT_LIMIT = 24;

export function recent(): string[] {
  try {
    const stored: unknown = JSON.parse(localStorage.getItem(RECENT_KEY) ?? "[]");
    return Array.isArray(stored) ? stored.filter((one): one is string => typeof one === "string") : [];
  } catch {
    return [];
  }
}

export function remember(emoji: string) {
  const kept = [emoji, ...recent().filter((one) => one !== emoji)].slice(0, RECENT_LIMIT);
  localStorage.setItem(RECENT_KEY, JSON.stringify(kept));
}
